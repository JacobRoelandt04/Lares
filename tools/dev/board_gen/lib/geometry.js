"use strict";
// geometry.js -- the generated geometry block (`// @@GEOM`): constants, the part table, the cast, the contact darkening, the traces, the scene's tail.
// The composition is generic; every piece that is a scene's own is a hook of its description (scenes/<name>.js):
//   scene.tool, scene.geometryLabel       what the generated header names
//   scene.groups                          group name -> id (GRP_<NAME> defines), in cast order
//   scene.constantsLines(G)               the numbers more than one shader leans on
//   scene.preludeLines(G)                 the scene's constants and anchors, after the part table
//   scene.extentGrow(p, G)                { x: [addends], y: [addends] }: how far a part reaches past its box when it moves (SCENE_MIN / MAX)
//   scene.groupFrame(G)                   the GLSL of the groups' frames (groupRay, flags, cutPart, groupNormal, inZone ...)
//   scene.aoBlock(G, opts)                the contact darkening (the board's pixel shader only; opts.glow: none)
//   scene.flowTables(G), scene.traceTailLines(G)    the glow's flow tables and the constants after the trace field
//   scene.tailLines(G)                    what follows the traces: the scene's own tables (cores, cells, displays ...)
//   + the cast's own (cast.js): generalGroups, basePart, shadowWeight, hitSign
const fmt = require("./fmt.js");
const { castBlocks } = require("./cast.js");
const { traceBlock } = require("./traces.js");

function geometryBlock(G, scene, opts) {
    opts = opts || {};
    const { f, v3 } = fmt;
    const GROUP = scene.groups;
    const L = [];
    L.push(`// ---- generated by ${scene.tool} from ${scene.geometryLabel} -- do not edit ----`);
    L.push(...scene.constantsLines(G));
    for (const k of Object.keys(G.MAT))
        L.push(`#define MAT_${k} ${G.MAT[k]}`);
    for (const k of Object.keys(GROUP))
        L.push(`#define GRP_${k.toUpperCase()} ${GROUP[k]}`);
    L.push(`#define PART_COUNT ${G.PARTS.length}`);
    G.PARTS.forEach((p, i) => L.push(`#define PART_${p.name.toUpperCase()} ${i}`));
    L.push(...scene.preludeLines(G));
    // the scene's bounding box (everything the camera ray can hit, the moving parts at the far end of their travel)
    const all = G.PARTS.reduce((a, p) => {
        const gx = scene.extentGrow(p, G);
        return {
            min: [Math.min(a.min[0], p.min[0]), Math.min(a.min[1], p.min[1]), Math.min(a.min[2], p.min[2])],
            max: [Math.max(a.max[0], gx.x.reduce((s, v) => s + v, p.max[0])), Math.max(a.max[1], gx.y.reduce((s, v) => s + v, p.max[1])), Math.max(a.max[2], p.max[2])]
        };
    }, { min: [1e9, 1e9, 1e9], max: [-1e9, -1e9, -1e9] });
    L.push(`const vec3 SCENE_MIN = ${v3(all.min)};`);
    L.push(`const vec3 SCENE_MAX = ${v3(all.max)};`);

    L.push(scene.groupFrame(G));
    const cast = castBlocks(G, scene, opts, fmt);
    L.push(cast.hit);
    L.push(cast.prim);
    if (cast.shad)
        L.push(cast.shad);
    if (!opts.glow)
        L.push(scene.aoBlock(G, opts));
    L.push(traceBlock(G, scene, opts, fmt));
    L.push(...scene.tailLines(G));
    L.push(`#define TRACE_COUNT ${G.TRACES.length}`);
    G.TRACES.forEach((t, id) => L.push(`#define TRACE_${t.name.replace(/[A-Z]/g, (c) => "_" + c).toUpperCase()} ${id}`));
    L.push("// ---- end of generated geometry ----");
    return L.join("\n");
}

module.exports = { geometryBlock };

#!/usr/bin/env node
// =============================================================================
// board_gen/gen.js -- assembles a scene's shaders from their sources and the ONE geometry. The board toolkit's generator (silicon's was the first scene;
// aerial's is the second): the machinery is generic, a scene is a description (scenes/<name>.js).
//
//   node tools/dev/board_gen/gen.js <scene>                 write <scene's outDir>/*.frag / *.vert
//   node tools/dev/board_gen/gen.js <scene> --check         exit 1 when a written shader is stale (gate)
//   node tools/dev/board_gen/gen.js <scene> <names>         only the shaders whose name contains one of these
//   (tools/dev/silicon_shader_gen.js [--check] [names] is `gen.js silicon`, kept for the gates and the docs that name it)
//
// Every shader that looks at the board is built from:
//   <scene.srcDir>/<name>.frag.in | .vert.in   its own template (whoever owns that shader)
//   the scene's geometry module                the boxes, traces, zone, anchors, written here as UNROLLED literal calls: a loop over a constant or
//                                              uniform array is scratch memory on an iGPU (CLAUDE.md "A LOCAL GLSL ARRAY ...")
//   *.glsl                                     pieces a template pulls in by name, from scene.includeDirs in order: the scene's own, then the toolkit's
//                                              (modules/common/board/shaders/)
// Markers in a template (a line by itself):
//   // @@GEOM              the generated geometry block (lib/geometry.js: constants, parts, the cast, the traces, the scene's tables)
//   // @@CONSTS            only the constants every shader may share: for a shader that does not look at the board and so must not pay for @@GEOM
//   // @@INCLUDE x.glsl    the file's text, verbatim
//   // @@<NAME>            a marker of the scene's own (scene.markers.<NAME>(G, ctx))
// The output carries a header naming its sources; it is committed and baked by tools/dev/bake_shaders.sh like every other .frag.
// What a scene must provide: modules/common/board/README.md "A new scene".
// =============================================================================
"use strict";
const fs = require("fs");
const path = require("path");
const { geometryBlock } = require("./lib/geometry.js");

function constantsBlock(G, scene) {
    return [`// ---- generated by ${scene.tool} from ${scene.geometryLabel} -- do not edit ----`]
        .concat(scene.constantsLines(G), ["// ---- end of generated constants ----"]).join("\n");
}

function findInclude(scene, file) {
    for (const d of scene.includeDirs) {
        const p = path.join(d, file);
        if (fs.existsSync(p))
            return p;
    }
    throw new Error(`${scene.name}: @@INCLUDE ${file} is in none of ${scene.includeDirs.join(", ")}`);
}

function assemble(name, G, scene) {
    const tpl = fs.readFileSync(path.join(scene.srcDir, name + ".in"), "utf8");
    const sources = [scene.sourceLabel(name + ".in", null), scene.geometrySourceLabel];
    const ctx = { sources, name };
    // an included piece may include others (a scene's materials file takes the toolkit's maths at the place they stand); a label of null keeps a file out of the header
    const expand = (text) => text.replace(/^[ \t]*\/\/ @@INCLUDE (\S+)[ \t]*$/gm, (m, file) => {
        const p = findInclude(scene, file);
        const label = scene.sourceLabel(file, p);
        if (label !== null)
            sources.push(label);
        return expand(fs.readFileSync(p, "utf8").replace(/\s+$/, ""));
    });
    let out = expand(tpl);
    out = out.replace(/^[ \t]*\/\/ @@GEOM[ \t]*$/m, () => geometryBlock(G, scene, scene.optsFor(name)));
    out = out.replace(/^[ \t]*\/\/ @@CONSTS[ \t]*$/m, () => constantsBlock(G, scene));
    for (const mk of Object.keys(scene.markers || {})) {
        out = out.replace(new RegExp("^[ \\t]*// @@" + mk + "[ \\t]*$", "m"), () => scene.markers[mk](G, ctx));
    }
    const header = `// GENERATED by ${scene.tool} -- edit the sources, then run it:\n//   ${sources.join("\n//   ")}\n`;
    // the #version line must stay first
    const m = out.match(/^(#version[^\n]*\n)/);
    return m ? m[1] + header + out.slice(m[1].length) : header + out;
}

function run(scene, argv) {
    const check = argv.includes("--check");
    const G = scene.loadGeometry();
    // optional name filters (`gen.js silicon silicon_holo`): a stream regenerates only the shaders it owns, so parallel streams never write each other's outputs
    const only = argv.filter((a) => !a.startsWith("--"));
    const names = fs.readdirSync(scene.srcDir).filter((n) => n.endsWith(".frag.in") || n.endsWith(".vert.in")).map((n) => n.slice(0, -3))
        .filter((n) => !only.length || only.some((o) => n.indexOf(o) >= 0));
    let stale = 0;
    for (const name of names) {
        const text = assemble(name, G, scene);
        const dst = path.join(scene.outDir, name);
        const old = fs.existsSync(dst) ? fs.readFileSync(dst, "utf8") : null;
        if (check) {
            if (old !== text) {
                console.log(`STALE ${name}`);
                stale++;
            } else {
                console.log(`ok    ${name}`);
            }
        } else if (old !== text) {
            fs.writeFileSync(dst, text);
            console.log(`wrote ${name}`);
        } else {
            console.log(`same  ${name}`);
        }
    }
    if (check) {
        console.log(`${scene.resultName} RESULT ${stale ? "FAIL (" + stale + " stale: run node " + scene.tool + ")" : "PASS (" + names.length + " shaders)"}`);
        process.exit(stale ? 1 : 0);
    }
}

function main() {
    const argv = process.argv.slice(2);
    const sceneName = argv.find((a) => !a.startsWith("--"));
    if (!sceneName) {
        console.log("usage: node tools/dev/board_gen/gen.js <scene> [--check] [names]   (scenes: " + fs.readdirSync(path.join(__dirname, "scenes")).map((n) => n.replace(/\.js$/, "")).join(", ") + ")");
        process.exit(2);
    }
    const scenePath = path.join(__dirname, "scenes", sceneName + ".js");
    if (!fs.existsSync(scenePath)) {
        console.log(`no scene "${sceneName}" (scenes/${sceneName}.js)`);
        process.exit(2);
    }
    argv.splice(argv.indexOf(sceneName), 1);
    run(require(scenePath), argv);
}

if (require.main === module)
    main();
module.exports = { assemble, constantsBlock, run };

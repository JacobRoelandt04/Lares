#!/usr/bin/env python3
"""tools/panorama/generate.py <setups.json> <engine.lua> <out.lua>

Writes ~/.config/hypr/config/panorama.lua (docs/contracts/panorama.md section 2): a header, `local PANORAMA_DATA_JSON = [=*[<data,
compact>]=*]`, and the verbatim text of the engine. The shell's EngineLink does the same through modules/panorama/data/EngineGenerate.js;
tools/dev/panorama_cases.lua holds both to the same bytes (the `-- generated:` line apart). The file is written atomically.
"""
import datetime
import json
import os
import re
import sys
import tempfile

HEADER = "-- Generated by Lares Panorama. Do not edit: use the Panorama popup.\n"


def _plain(v):
    """The JS model's numbers: an integral float prints as an integer (1.0 -> 1), as JSON.stringify does."""
    if isinstance(v, float) and v.is_integer():
        return int(v)
    if isinstance(v, dict):
        return {k: _plain(x) for k, x in v.items()}
    if isinstance(v, list):
        return [_plain(x) for x in v]
    return v


def compact(text):
    return json.dumps(_plain(json.loads(text)), sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def bracketed(text):
    """A Lua long string; a text that ends in "]" must not close it early (EngineGenerate.js has the same rule)."""
    n = 0
    while "]" + "=" * n + "]" in text + "]":
        n += 1
    return "[" + "=" * n + "[" + text + "]" + "=" * n + "]"


def engine_version(engine):
    m = re.search(r"^local ENGINE_VERSION = (\d+)", engine, re.M)
    if not m:
        raise SystemExit("generate.py: the engine has no `local ENGINE_VERSION = N` line")
    return m.group(1)


def generate(setups_text, engine_text, now=None):
    now = now or datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    return (HEADER + "-- engine version: " + engine_version(engine_text) + "\n-- generated: " + now + "\n"
            + "local PANORAMA_DATA_JSON = " + bracketed(compact(setups_text)) + "\n" + engine_text)


def main(argv):
    if len(argv) != 4:
        print(__doc__)
        return 2
    with open(argv[1], encoding="utf-8") as f:
        setups = f.read()
    with open(argv[2], encoding="utf-8") as f:
        engine = f.read()
    out = generate(setups, engine)
    d = os.path.dirname(os.path.abspath(argv[3]))
    os.makedirs(d, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".panorama-", suffix=".tmp", dir=d)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(out)
        os.chmod(tmp, 0o644)
        os.rename(tmp, argv[3])
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
